# For DMC: each of the 12 grid edges is shared by 4 cells.
# EDGE_AXIS[e] = axis (0=x, 1=y, 2=z) of edge e.
# EDGE_CELL_OFFSETS[e] = [4, 3], the 4 cell offsets (relative to edge's
# "anchor" cell) that share this edge, used for quad emission.
#
# An edge along axis a at grid position (ex, ey, ez) is shared by cells:
#   (ex + dx, ey + dy, ez + dz) for each (dx, dy, dz) in EDGE_CELL_OFFSETS[a]
#
# For axis=0 (x-edge): shared by cells offset in (y, z) = {(0,0),(-1,0),(0,-1),(-1,-1)}
# For axis=1 (y-edge): shared by cells offset in (x, z) = {(0,0),(-1,0),(0,-1),(-1,-1)}
