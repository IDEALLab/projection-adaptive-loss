# Precomputed [256, 12] table: for each MC case and each edge, which vertex
# slot (0-3) owns that edge. Derived from _DUAL_POINTS_LIST.
# Edges not active for a case get slot 0 (harmless, they're never queried).
_CASE_EDGE_TO_SLOT = [[0] * 12 for _ in range(256)]
for _case in range(256):
    for _s in range(4):
        _mask = _DUAL_POINTS_LIST[_case][_s]
        for _e in range(12):
            if _mask & (1 << _e):
                _CASE_EDGE_TO_SLOT[_case][_e] = _s

# Per-device cache
_cache: dict[torch.device, tuple[Tensor, ...]] = {}


def get_tables(device: torch.device) -> tuple[Tensor, ...]:
    """
    Return all DMC tables on the given device (cached per device).

    Returns:
        corner_offsets:      [8, 3]      int32
        edge_corners:        [12, 2]     int32
        edge_table:          [256]       int32
        edge_axis:           [12]        int32
        quad_cell_offsets:   [3, 4, 3]   int32
        dual_points_list:    [256, 4]    int32  (manifold DMC: edge masks per slot)
        problematic_configs: [256]       int32  (manifold DMC: ambiguity direction)
        num_dual_points:     [256]       int32  (manifold DMC: slot count per case)
        quad_local_edges:    [3, 4]      int32  (manifold DMC: local edge per axis)
        case_edge_to_slot:   [256, 12]   int32  (edge -> slot mapping per case)
    """
    if device not in _cache:
        _cache[device] = (
            torch.tensor(_CORNER_OFFSETS, dtype=torch.int32, device=device),
            torch.tensor(_EDGE_CORNERS, dtype=torch.int32, device=device),
            torch.tensor(_EDGE_TABLE, dtype=torch.int32, device=device),
            torch.tensor(_EDGE_AXIS, dtype=torch.int32, device=device),
            torch.tensor(_QUAD_CELL_OFFSETS, dtype=torch.int32, device=device),
            torch.tensor(_DUAL_POINTS_LIST, dtype=torch.int32, device=device),
            torch.tensor(_PROBLEMATIC_CONFIGS, dtype=torch.int32, device=device),
            torch.tensor(_NUM_DUAL_POINTS, dtype=torch.int32, device=device),
            torch.tensor(_QUAD_LOCAL_EDGES, dtype=torch.int32, device=device),
            torch.tensor(_CASE_EDGE_TO_SLOT, dtype=torch.int32, device=device),
        )
    return _cache[device]
